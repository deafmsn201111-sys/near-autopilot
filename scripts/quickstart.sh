#!/usr/bin/env bash
# NEAR Autopilot - one command from a fresh clone to the running site. Needs Docker (Compose v2) only.
#
#   ./scripts/quickstart.sh
#
# What it does, and does not:
#   - creates .env from .env.example ONLY if .env does not exist, with fresh random secrets (never printed); an
#     existing .env is never touched
#   - builds and starts the containers (bound to 127.0.0.1) and waits until they are healthy
#   - never creates a wallet key, never signs, never sends a transaction; mainnet is read with view calls only
set -euo pipefail
cd "$(dirname "$0")/.."

case "${1:-}" in
  "") ;;
  -h | --help)
    sed -n '2,10p' "$0"
    exit 0
    ;;
  *)
    echo "unknown option: $1" >&2
    exit 2
    ;;
esac

command -v docker >/dev/null || { echo "Docker is required: https://docs.docker.com/get-docker/" >&2; exit 1; }
docker compose version >/dev/null 2>&1 || { echo "Docker Compose v2 is required (docker compose ...)" >&2; exit 1; }

rand() { # hex secret of $1 bytes, without echoing it anywhere
  if command -v openssl >/dev/null; then openssl rand -hex "$1"; else od -An -tx1 -N"$1" /dev/urandom | tr -d ' \n'; fi
}
set_var() { # set_var KEY VALUE in .env (value is a hex/plain token: no sed metacharacters)
  if grep -q "^$1=" .env; then
    sed -i.bak "s|^$1=.*|$1=$2|" .env && rm -f .env.bak
  else
    printf '%s=%s\n' "$1" "$2" >>.env
  fi
}

if [ -f .env ]; then
  echo "• .env exists: using it as it is"
else
  cp .env.example .env
  pw="$(rand 24)"
  set_var API_TOKEN "$(rand 32)"
  set_var POSTGRES_PASSWORD "$pw"
  set_var DATABASE_URL "postgres://autopilot:${pw}@localhost:5432/autopilot"
  chmod 600 .env
  echo "• .env created with fresh secrets (not shown)"
fi

grep -q '^ADMIN_API_TOKEN=.' .env || { set_var ADMIN_API_TOKEN "$(rand 32)"; echo "• ADMIN_API_TOKEN added to .env (not shown)"; }

mkdir -p evidence/checkpoints

echo "• building and starting containers (first run: a few minutes)…"
# Signing key for the audit checkpoints: generated by the project's own image, appended to .env, never printed and
# never stored in the database (see apps/api/src/evidence/checkpoint.ts).
if ! grep -q '^AUDIT_CHECKPOINT_KEY=.' .env; then
  docker compose build analytics-api >/dev/null
  docker compose run --rm --no-deps -T analytics-api node --import tsx src/evidence/cli.ts checkpoint-keygen >>.env
  echo "• audit checkpoint signing key created in .env (not shown)"
fi
docker compose up -d --build

echo "• waiting for the services to be healthy…"
deadline=$((SECONDS + 600))
while true; do
  states="$(docker compose ps --format '{{.Service}} {{.Health}}')"
  if ! grep -qv ' healthy$' <<<"$states"; then break; fi
  if [ $SECONDS -gt $deadline ]; then
    echo "not healthy after 10 minutes:" >&2
    grep -v ' healthy$' <<<"$states" >&2
    echo "logs: docker compose logs <service>" >&2
    exit 1
  fi
  sleep 3
done

port="${ANALYTICS_DASHBOARD_PORT:-$(grep '^ANALYTICS_DASHBOARD_PORT=' .env | cut -d= -f2- || true)}"
echo
echo "Ready. Everything is bound to 127.0.0.1; the server never signs or sends anything."
echo "  Site   http://127.0.0.1:${port:-3001}"
echo "  Admin  http://127.0.0.1:${ANALYTICS_ADMIN_PORT:-3002}/admin   (AI spend and kill switch, loopback only)"
echo "  (the mainnet collector fills the market pages within its first cycle, ~1-2 minutes)"
echo "Stop: docker compose stop   (data is kept)"
