import type { Metadata } from 'next';
import { Geist, Geist_Mono } from 'next/font/google';
import { cookies, headers } from 'next/headers';
import Link from 'next/link';
import type { ReactNode } from 'react';
import { AutoRefresh } from '../components/AutoRefresh';
import { SubNav, TabBar, TopNav } from '../components/Nav';
import { ThemeToggle } from '../components/ThemeToggle';
import { WalletButton } from '../components/WalletButton';
import { THEME_COLOR, THEME_SCRIPT } from '../lib/theme';
import './globals.css';

const geist = Geist({ subsets: ['latin'], variable: '--font-geist' });
const geistMono = Geist_Mono({ subsets: ['latin'], variable: '--font-geist-mono' });

export const metadata: Metadata = {
  title: 'NEAR Autopilot',
  description:
    'An autopilot for your NEAR DeFi portfolio: it watches Burrow and Rhea, finds what is worth doing, and explains every decision.',
  robots: { index: false, follow: false },
};

export const dynamic = 'force-dynamic';

export default async function RootLayout({ children }: { children: ReactNode }) {
  const nonce = (await headers()).get('x-nonce') ?? undefined;
  const account = (await cookies()).get('np_account')?.value || null;
  return (
    <html lang="en" className={`${geist.variable} ${geistMono.variable}`} suppressHydrationWarning>
      <head>
        <meta name="theme-color" content={THEME_COLOR.dark} suppressHydrationWarning />
        <script nonce={nonce} dangerouslySetInnerHTML={{ __html: THEME_SCRIPT }} />
      </head>
      <body>
        <header className="app-top">
          <div className="app-top-in">
            <Link href="/" className="app-logo">
              <svg viewBox="0 0 22 22" aria-hidden="true">
                <rect x="1" y="1" width="20" height="20" rx="6" fill="currentColor" />
                <path d="M6.5 15.5 11 5.5l4.5 10-4.5-2.4z" fill="var(--bg-page)" />
              </svg>
              NEAR Autopilot
            </Link>
            <TopNav />
            <div className="app-top-right">
              <ThemeToggle />
              <WalletButton initialAccount={account} />
            </div>
          </div>
        </header>
        <main className="page">
          <SubNav />
          {children}
        </main>
        <footer className="disclaimer">
          <p>
            Not financial advice. Recommendations are generated by heuristics and AI and can be
            wrong. Nothing runs on its own: NEAR Autopilot never holds your keys, every transaction
            is built unsigned and signed by you in your own wallet, at your own risk. DeFi protocols
            (Burrow, Rhea, liquid staking) carry smart-contract, oracle, liquidation,
            impermanent-loss and slippage risk. Unaudited hackathon software, provided as is (MIT).
          </p>
          <p className="app-foot-reviewers">
            <Link href="/reviewers">For reviewers</Link>: the safety policy, audit trail and
            research behind every number.
          </p>
        </footer>
        <TabBar />
        <AutoRefresh seconds={15} />
      </body>
    </html>
  );
}
