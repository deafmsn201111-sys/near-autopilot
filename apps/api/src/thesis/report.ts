import type { PoolMetrics } from './analysis';
import type { ThesisData } from './rebuild';
import { tokenLabel } from './labels';

/**
 * THESIS.md, generated. Every number comes from `ThesisData`; the verdict follows from the falsification rules stated
 * in the document (fixed BEFORE the data was looked at), not from wording chosen afterwards.
 */
const p = (v: number | null, d = 1) =>
  v === null || !Number.isFinite(v) ? 'n/a' : `${(v * 100).toFixed(d)}%`;
const pp = (v: number | null) =>
  v === null || !Number.isFinite(v) ? 'n/a' : `${(v * 100).toFixed(1)} pp`;
const usd = (v: number | null) =>
  v === null
    ? 'n/a'
    : `$${
        v >= 1000
          ? Math.round(v)
              .toString()
              .replace(/\B(?=(\d{3})+(?!\d))/g, ',')
          : v.toFixed(2)
      }`;
const med = (xs: readonly number[]) => {
  const s = [...xs].filter(Number.isFinite).sort((a, b) => a - b);
  if (s.length === 0) return null;
  const m = Math.floor(s.length / 2);
  return s.length % 2 ? (s[m] ?? null) : ((s[m - 1] ?? 0) + (s[m] ?? 0)) / 2;
};
const name = (m: PoolMetrics) => `#${m.pool} wNEAR/${tokenLabel(m.other)}`;

/** The falsification rules, fixed in advance. */
export const RULES = {
  /** H1 is falsified if the nominal 24h APR is within this distance of LP vs HODL in at least half of the pools. */
  closeEnoughPp: 0.02,
  /** H2 is falsified if TVL rank predicts the LP outcome this strongly (|Spearman ρ| at or above). */
  strongRho: 0.7,
  /** H3 is falsified if Burrow's displayed supply APR is within this of the realized one in at least 3/4 of markets. */
  burrowCloseEnoughPp: 0.005,
} as const;

/** The three counts and their falsification results: one calculation for THESIS.md and the dashboard. */
export function thesisSummary(d: ThesisData) {
  const pools = [...d.pools].sort((a, b) => b.tvlNearEnd - a.tvlNearEnd);
  const n = pools.length;
  const withNominal = pools.filter((m) => m.nominalApr24hEnd !== null);
  const above = withNominal.filter((m) => (m.nominalApr24hEnd ?? 0) > m.lpVsHodlApr);
  const close = withNominal.filter(
    (m) => Math.abs((m.nominalApr24hEnd ?? 0) - m.lpVsHodlApr) <= RULES.closeEnoughPp,
  );
  const h1 = close.length < withNominal.length / 2;
  const rho = d.tvlVsNet;
  const h2 = rho !== null && Math.abs(rho) < RULES.strongRho;
  const markets = d.burrow.filter((b) => b.supplyAprEnd > 0 || b.supplyAprRealized > 0);
  const bClose = markets.filter(
    (b) => Math.abs(b.supplyAprEnd - b.supplyAprRealized) <= RULES.burrowCloseEnoughPp,
  );
  const h3 = markets.length > 0 && bClose.length < (markets.length * 3) / 4;
  const negative500 = pools.filter((m) => m.netApr500 !== null && m.netApr500 < 0);
  const negativeHodl = pools.filter((m) => m.lpVsHodlApr < 0);
  const spread = pools.flatMap((m) =>
    m.nominalApr24hMax !== null && m.nominalApr24hMin !== null
      ? [m.nominalApr24hMax - m.nominalApr24hMin]
      : [],
  );
  const idle = pools.filter((m) => m.nominalApr24hMedian !== null && m.nominalApr24hMedian < 0.005);
  const verdict = [h1, h2, h3].filter(Boolean).length;
  const verdictText =
    verdict === 3
      ? 'SUPPORTED on all three counts'
      : verdict === 0
        ? 'NOT SUPPORTED'
        : `PARTLY SUPPORTED (${verdict} of 3 counts)`;
  return {
    pools,
    n,
    withNominal,
    above,
    close,
    h1,
    rho,
    h2,
    markets,
    bClose,
    h3,
    negative500,
    negativeHodl,
    spread,
    idle,
    verdict,
    verdictText,
  };
}

